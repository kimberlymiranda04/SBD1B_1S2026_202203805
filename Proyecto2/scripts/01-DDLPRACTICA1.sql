CREATE TABLE DEPARTAMENTO (
    codigo INTEGER PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL
);

CREATE TABLE MUNICIPIO (
    codigo INTEGER PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    departamento_codigo INTEGER NOT NULL,
    CONSTRAINT fk_muni_depto FOREIGN KEY (departamento_codigo) REFERENCES DEPARTAMENTO(codigo)
);

CREATE TABLE CENTRO (
    id_centro INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    nombre    VARCHAR2(200) NOT NULL
);

CREATE TABLE ESCUELA (
    id_escuela INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    nombre     VARCHAR2(200) NOT NULL,
    direccion  VARCHAR2(500),
    acuerdo    VARCHAR2(50)
);

CREATE TABLE UBICACION (
    escuela_id_escuela INTEGER NOT NULL,
    centro_id_centro   INTEGER NOT NULL,
    PRIMARY KEY (escuela_id_escuela, centro_id_centro), 
    CONSTRAINT fk_ubica_escuela FOREIGN KEY (escuela_id_escuela) REFERENCES ESCUELA(id_escuela),
    CONSTRAINT fk_ubica_centro FOREIGN KEY (centro_id_centro) REFERENCES CENTRO(id_centro)
);

CREATE TABLE REGISTRO (
    id_registro                            INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    ubicacion_escuela_id_escuela           INTEGER NOT NULL,
    ubicacion_centro_id_centro             INTEGER NOT NULL,
    municipio_id_municipio                 INTEGER NOT NULL,
    municipio_departamento_id_departamento INTEGER NOT NULL, 
    fecha                                  DATE,
    tipo_tramite                           VARCHAR2(100),
    tipo_licencia                          VARCHAR2(5),
    nombre_completo                        VARCHAR2(250),
    genero                                 CHAR(1), 
    CONSTRAINT fk_reg_ubica FOREIGN KEY (ubicacion_escuela_id_escuela, ubicacion_centro_id_centro) REFERENCES UBICACION(escuela_id_escuela, centro_id_centro),
    CONSTRAINT fk_reg_muni FOREIGN KEY (municipio_id_municipio) REFERENCES MUNICIPIO(codigo),
    CONSTRAINT fk_reg_depto FOREIGN KEY (municipio_departamento_id_departamento) REFERENCES DEPARTAMENTO(codigo)
);

CREATE TABLE CORRELATIVO (
    id_correlativo INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    fecha          DATE,
    no_examen      INTEGER
);

CREATE TABLE EXAMEN (
    id_examen                       INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    registro_id_registro            INTEGER NOT NULL,
    correlativo_id_correlativo      INTEGER NOT NULL,
    registro_id_escuela             INTEGER NOT NULL,
    registro_id_centro              INTEGER NOT NULL,
    registro_municipio_id_municipio INTEGER NOT NULL,
    registro_muni_depto_id_depto    INTEGER NOT NULL, 
    CONSTRAINT fk_exam_reg FOREIGN KEY (registro_id_registro) REFERENCES REGISTRO(id_registro),
    CONSTRAINT fk_exam_corr FOREIGN KEY (correlativo_id_correlativo) REFERENCES CORRELATIVO(id_correlativo),
    CONSTRAINT fk_exam_escuela FOREIGN KEY (registro_id_escuela) REFERENCES ESCUELA(id_escuela),
    CONSTRAINT fk_exam_centro FOREIGN KEY (registro_id_centro) REFERENCES CENTRO(id_centro),
    CONSTRAINT fk_exam_muni FOREIGN KEY (registro_municipio_id_municipio) REFERENCES MUNICIPIO(codigo),
    CONSTRAINT fk_exam_depto FOREIGN KEY (registro_muni_depto_id_depto) REFERENCES DEPARTAMENTO(codigo)
);

CREATE TABLE PREGUNTAS (
    id_pregunta        INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    pregunta_texto     VARCHAR2(1000) NOT NULL,
    respuesta_a        VARCHAR2(500),
    respuesta_b        VARCHAR2(500),
    respuesta_c        VARCHAR2(500),
    respuesta_d        VARCHAR2(500),
    respuesta_correcta CHAR(1)
);

CREATE TABLE PREGUNTAS_PRACTICO (
    id_pregunta_practico INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    pregunta_texto       VARCHAR2(1000) NOT NULL,
    punteo               INTEGER
);

CREATE TABLE RESPUESTA_USUARIO (
    id_resp_user         INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    pregunta_id_pregunta INTEGER NOT NULL,
    examen_id_examen     INTEGER NOT NULL,
    respuesta            CHAR(1),
    CONSTRAINT fk_resp_preg FOREIGN KEY (pregunta_id_pregunta) REFERENCES PREGUNTAS(id_pregunta),
    CONSTRAINT fk_resp_exam FOREIGN KEY (examen_id_examen) REFERENCES EXAMEN(id_examen)
);

CREATE TABLE RESPUESTA_PRACTICO_USUARIO (
    id_resp_pract_user                     INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NOCACHE) PRIMARY KEY,
    pregunta_practico_id_pregunta_practico INTEGER NOT NULL,
    examen_id_examen                       INTEGER NOT NULL,
    nota                                   INTEGER,
    CONSTRAINT fk_pract_preg FOREIGN KEY (pregunta_practico_id_pregunta_practico) REFERENCES PREGUNTAS_PRACTICO(id_pregunta_practico),
    CONSTRAINT fk_pract_exam FOREIGN KEY (examen_id_examen) REFERENCES EXAMEN(id_examen)
);

